// Extracts the prompt heredocs VERBATIM from the SaaS backend (read-only) into src/prompts/php.ts.
// Usage: node scripts/extract-php-prompts.mjs [--check]   (backend path: env BILIMIND_BACKEND or ../../../backend)
// --check: exit 1 when src/prompts/php.ts differs from a fresh extraction (used by the golden test too).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const backend = process.env.BILIMIND_BACKEND ?? resolve(here, '..', '..', '..', '..', 'backend');
const PROMPTS = join(backend, 'app', 'Services', 'Llm', 'Prompts');
const FILES = ['PromptSupport', 'OutlinePrompt', 'ArchetypeRelabelPrompt', 'ExpandNodePrompt'];

/** Every heredoc/nowdoc in a PHP file as {key: 'Class.function.n', text, nowdoc}. */
export function extractHeredocs(src, cls) {
  const out = [];
  const re = /<<<(['"]?)([A-Z]+)\1\n([\s\S]*?)\n([ \t]*)\2(?=[;,)\s])/g;
  const counts = {};
  let m;
  while ((m = re.exec(src))) {
    const before = src.slice(0, m.index);
    const fns = [...before.matchAll(/function\s+(\w+)\s*\(/g)];
    const fn = fns.length ? fns[fns.length - 1][1] : 'top';
    const indent = m[4];
    const lines = m[3].split('\n').map(l => (l.startsWith(indent) ? l.slice(indent.length) : l.trimStart()));
    const n = (counts[fn] = (counts[fn] ?? -1) + 1);
    out.push({ key: `${cls}.${fn}.${n}`, text: lines.join('\n'), nowdoc: m[1] === "'" });
  }
  return out;
}

export function extractAll(dir = PROMPTS) {
  const all = {};
  for (const f of FILES) {
    const src = readFileSync(join(dir, `${f}.php`), 'utf8').replace(/\r\n/g, '\n');
    for (const h of extractHeredocs(src, f)) all[h.key] = h.text;
  }
  return all;
}

function render(all) {
  const body = Object.entries(all).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  return `// GENERATED by scripts/extract-php-prompts.mjs from backend/app/Services/Llm/Prompts/*.php. DO NOT EDIT.
// The production prompt heredocs, verbatim (PHP placeholders like {$house} kept). Composition and the
// HACKATHON edits live in src/prompts/{support,outline,expand}.ts.
export const PHP_PROMPTS = {
${body}
} as const;
export type PhpPromptKey = keyof typeof PHP_PROMPTS;
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (!existsSync(PROMPTS)) { console.error(`backend prompts not found at ${PROMPTS}`); process.exit(2); }
  const target = join(here, '..', 'src', 'prompts', 'php.ts');
  const text = render(extractAll());
  if (process.argv.includes('--check')) {
    const same = existsSync(target) && readFileSync(target, 'utf8') === text;
    console.log(same ? 'php.ts is up to date' : 'php.ts DIFFERS from the backend heredocs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(target, text);
  console.log(`wrote ${target} (${Object.keys(extractAll()).length} heredocs)`);
}
