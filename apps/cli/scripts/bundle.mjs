// esbuild the CLI + engine + core into ONE file that runs with no node_modules (WorkBuddy's bundled Node 22 or Node 24):
//   skills/bilimind/scripts/bilimind.mjs   (+ sql-wasm.wasm next to it, for sql.js)
//   skills/bilimind/templates/player.html  (from packages/player/dist/player.html)
//   skills/bilimind/assets/obj-*.webp      (the 3D objects build copies into each course's img/)
// Usage: node apps/cli/scripts/bundle.mjs [--minify] [--out <skill dir>]
// Quirks handled: ESM bundle of CJS deps needs require/__dirname/__filename (banner); ws's optional native addons
// (bufferutil, utf-8-validate) stay external (required inside try/catch, so absence is fine); sql.js finds its
// wasm via __dirname, so the wasm is copied next to the bundle.
import { build } from 'esbuild';
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const cliDir = join(here, '..');
const repo = join(cliDir, '..', '..');
const argv = process.argv.slice(2);
const outIdx = argv.indexOf('--out');
const skill = outIdx >= 0 ? resolve(argv[outIdx + 1]) : join(repo, 'skills', 'bilimind');
const minify = argv.includes('--minify');
const outfile = join(skill, 'scripts', 'bilimind.mjs');
for (const d of ['scripts', 'templates', 'assets']) mkdirSync(join(skill, d), { recursive: true });

const banner = [
  '// bilimind.mjs: BiliMind for WorkBuddy CLI (generated by apps/cli/scripts/bundle.mjs; do not edit). AGPL-3.0-only.',
  "import { createRequire as __bmCreateRequire } from 'node:module';",
  "import { fileURLToPath as __bmFileURLToPath } from 'node:url';",
  "import { dirname as __bmDirname } from 'node:path';",
  'const require = __bmCreateRequire(import.meta.url);',
  'const __filename = __bmFileURLToPath(import.meta.url);',
  'const __dirname = __bmDirname(__filename);',
].join('\n');

const t0 = Date.now();
const result = await build({
  entryPoints: [join(cliDir, 'src', 'main.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  banner: { js: banner },
  external: ['bufferutil', 'utf-8-validate'],
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  minifyWhitespace: minify,
  minifySyntax: minify,
  metafile: true,
  logLevel: 'warning',
});
const kb = f => Math.round(statSync(f).size / 1024);
console.log(`bundle: ${relative(repo, outfile)} ${kb(outfile)} KB in ${Date.now() - t0} ms`);
if (argv.includes('--meta')) writeFileSync(join(cliDir, 'bundle-meta.json'), JSON.stringify(result.metafile));

// sql.js: copy its node wasm next to the bundle (it is located via __dirname at runtime)
const engineRequire = createRequire(join(repo, 'packages', 'engine', 'package.json'));
try {
  const sqlMain = engineRequire.resolve('sql.js');
  const wasm = join(dirname(sqlMain), 'sql-wasm.wasm');
  if (existsSync(wasm)) { copyFileSync(wasm, join(skill, 'scripts', 'sql-wasm.wasm')); console.log(`wasm: scripts/sql-wasm.wasm ${kb(wasm)} KB`); }
} catch { console.warn('sql.js not resolvable from packages/engine: no wasm copied'); }

// player template
const tpl = join(repo, 'packages', 'player', 'dist', 'player.html');
if (existsSync(tpl)) { copyFileSync(tpl, join(skill, 'templates', 'player.html')); console.log(`template: templates/player.html ${kb(tpl)} KB`); }
else console.warn('packages/player/dist/player.html missing: run `pnpm -F @bilimind/player build` first');

// 3D objects
const objDirs = [join(repo, 'packages', 'player', 'public', 'img'), join(repo, 'plan', 'reference', 'design', 'hero-v7', 'img', '11')];
const objDir = objDirs.find(d => existsSync(d) && readdirSync(d).some(f => /^obj-.*\.webp$/.test(f)));
if (objDir) {
  const objs = readdirSync(objDir).filter(f => /^obj-.*\.webp$/.test(f));
  for (const f of objs) copyFileSync(join(objDir, f), join(skill, 'assets', f));
  console.log(`assets: ${objs.length} objects from ${relative(repo, objDir)}`);
} else console.warn('no obj-*.webp found');
